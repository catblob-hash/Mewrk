#!/usr/bin/env python3
"""Distils material-icon-theme's manifest into src/icon_table.rs and copies the icons it names, the job upstream's
scripts/vite-file-icons.mjs does at build time. Run it again when the theme is upgraded: python3 gen_file_icons.py <package dir>"""
import json, os, shutil, sys

package = sys.argv[1]
manifest_path = os.path.join(package, "dist", "material-icons.json")
here = os.path.dirname(os.path.abspath(__file__))
crate = os.path.dirname(here)
theme = json.load(open(manifest_path))
lower = lambda table: {k.lower(): v for k, v in table.items()}
names, exts = lower(theme["fileNames"]), lower(theme["fileExtensions"])
light = set()
for table, light_table in ((names, lower(theme["light"].get("fileNames", {}))), (exts, lower(theme["light"].get("fileExtensions", {})))):
    for key, icon in light_table.items():
        base = table.get(key)
        if icon != f"{base}_light":
            raise SystemExit(f"{icon} ({key}) is not the _light variant of {base}")
        light.add(base)
icons = {theme["file"], *names.values(), *exts.values()} | {f"{i}_light" for i in light}
out_dir = os.path.join(crate, "assets", "file-icons")
shutil.rmtree(out_dir, ignore_errors=True)
os.makedirs(out_dir)
for icon in sorted(icons):
    source = os.path.normpath(os.path.join(os.path.dirname(manifest_path), theme["iconDefinitions"][icon]["iconPath"]))
    shutil.copy(source, os.path.join(out_dir, f"{icon}.svg"))
shutil.copy(os.path.join(package, "LICENSE"), os.path.join(crate, "assets", "file-icons", "LICENSE"))
pair = lambda k, v: f"    ({json.dumps(k, ensure_ascii=False)}, {json.dumps(v)}),\n"
with open(os.path.join(crate, "src", "icon_table.rs"), "w") as f:
    f.write("//! Generated by scripts/gen_file_icons.py from material-icon-theme. Do not edit.\n\n")
    f.write(f"pub const FALLBACK: &str = {json.dumps(theme['file'])};\n")
    f.write(f"pub const NAME_DEPTH: usize = {max(k.count('/') + 1 for k in names)};\n\n")
    f.write("/// Whole file names, optionally with the directories above them. Sorted by key.\npub const NAMES: &[(&str, &str)] = &[\n")
    f.writelines(pair(k, names[k]) for k in sorted(names, key=lambda s: s.encode()))
    f.write("];\n\n/// Extensions, sorted by key.\npub const EXTENSIONS: &[(&str, &str)] = &[\n")
    f.writelines(pair(k, exts[k]) for k in sorted(exts, key=lambda s: s.encode()))
    f.write("];\n\n/// Icons with a second drawing for light backgrounds. Sorted.\npub const LIGHT: &[&str] = &[\n")
    f.writelines(f"    {json.dumps(i)},\n" for i in sorted(light))
    f.write("];\n\n/// Every drawing, sorted by name.\npub const ICONS: &[(&str, &str)] = &[\n")
    f.writelines(f'    ({json.dumps(i)}, include_str!("../assets/file-icons/{i}.svg")),\n' for i in sorted(icons, key=lambda s: s.encode()))
    f.write("];\n")
print(len(names), len(exts), len(light), len(icons))
