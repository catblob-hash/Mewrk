//! The Claude Code plugin that keeps the CLI's own context out of the prompt (`claude-context-plugin.ts`).
//!
//! Left to itself the CLI attaches context it authors (an `# Environment` block, a model-identity line, today's
//! date) to the first user message. Only the host knows which facts hold for which machine, so the host's prompt
//! is the only one the model may see. A plugin's hooks module may answer the `prompt.attachment` event with
//! `{ text: null }`; this one does for everything but `deferred_tools_delta`, the attachment that carries a tool
//! which joined mid-session. The files are generated here and written content-addressed under `agent.cwd`: a
//! directory named by the digest of its contents is complete or absent.

use std::collections::HashMap;
use std::fs;
use std::path::{MAIN_SEPARATOR, Path, PathBuf};
use std::sync::{Mutex, OnceLock};

use graviola::hashing::{Hash, HashContext, Sha256};

use super::shapes::random_uuid;

/// Plugin name; the CLI reports it as `mewrk-context@inline`.
const CONTEXT_PLUGIN_NAME: &str = "mewrk-context";
/// Parent directory of the plugin, under the session directory.
const PLUGINS_DIR: &str = "plugins";

/// The hooks module, byte for byte: the digest names the directory.
const HOOKS_MODULE: &str = r#"// Generated by Mewrk (aisdk-service/src/claude-context-plugin.ts).
const PASSED = ["deferred_tools_delta"];
export const register = (on) => {
  on("prompt.attachment", ($, e, next) => (PASSED.includes(e.type) ? next(e) : { text: null }));
};
"#;

const PLUGIN_JSON: &str = r#"{
  "name": "mewrk-context",
  "version": "1.0.0",
  "description": "Leaves Claude Code's own context out of the prompt, except the tool additions it makes mid-session; Mewrk supplies its own."
}
"#;

const HOOKS_JSON: &str = r#"{
  "modules": [
    "./context.ts"
  ]
}
"#;

/// Plugin files by path relative to the plugin root. `path.join`, so the separator is the platform's, in the digest
/// too.
fn plugin_files() -> [(String, &'static str); 3] {
    [
        (format!(".claude-plugin{MAIN_SEPARATOR}plugin.json"), PLUGIN_JSON),
        (format!("hooks{MAIN_SEPARATOR}hooks.json"), HOOKS_JSON),
        (format!("hooks{MAIN_SEPARATOR}context.ts"), HOOKS_MODULE),
    ]
}

/// The first 16 hex digits of the SHA-256 of every file's path and text.
fn digest() -> String {
    let mut hash = Sha256::new();
    for (relative, text) in plugin_files() {
        hash.update(relative.as_bytes());
        hash.update(b"\0");
        hash.update(text.as_bytes());
        hash.update(b"\0");
    }
    let output = hash.finish();
    output.as_ref().iter().take(8).map(|byte| format!("{byte:02x}")).collect()
}

fn is_complete(dir: &Path) -> bool {
    plugin_files().iter().all(|(relative, text)| fs::read(dir.join(relative)).is_ok_and(|found| found == text.as_bytes()))
}

/// Earlier builds' copies and staging left by a crash; nothing else lives under `plugins/`.
fn remove_stale(parent: &Path, current: &str) {
    let Ok(entries) = fs::read_dir(parent) else { return };
    let prefix = format!("{CONTEXT_PLUGIN_NAME}-");
    for entry in entries.flatten() {
        let name = entry.file_name().to_string_lossy().into_owned();
        if name == current || !name.strip_prefix('.').unwrap_or(&name).starts_with(&prefix) {
            continue;
        }
        let path = entry.path();
        if path.is_dir() {
            let _ = fs::remove_dir_all(&path);
        } else {
            let _ = fs::remove_file(&path);
        }
    }
}

fn write_staged(staging: &Path) -> std::io::Result<()> {
    for (relative, text) in plugin_files() {
        let file = staging.join(relative);
        if let Some(parent) = file.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(file, text)?;
    }
    Ok(())
}

fn materialized() -> &'static Mutex<HashMap<String, PathBuf>> {
    static MATERIALIZED: OnceLock<Mutex<HashMap<String, PathBuf>>> = OnceLock::new();
    MATERIALIZED.get_or_init(|| Mutex::new(HashMap::new()))
}

/// `contextPluginDir`: the plugin directory under `root`, written on first use. Staged beside its final name and
/// renamed into place, so the CLI never loads a half-written copy. An error means the session must not start: without
/// the plugin the model would see the CLI's context.
pub(super) fn context_plugin_dir(root: &str) -> Result<PathBuf, String> {
    let known = materialized().lock().unwrap_or_else(|p| p.into_inner()).get(root).cloned();
    if let Some(known) = known.filter(|dir| is_complete(dir)) {
        return Ok(known);
    }
    let parent = Path::new(root).join(PLUGINS_DIR);
    let name = format!("{CONTEXT_PLUGIN_NAME}-{}", digest());
    let dir = parent.join(&name);
    if !is_complete(&dir) {
        let _ = fs::remove_dir_all(&dir);
        let staging = parent.join(format!(".{name}.{}", random_uuid()));
        let written = write_staged(&staging).and_then(|()| fs::rename(&staging, &dir));
        let _ = fs::remove_dir_all(&staging);
        written.map_err(|error| format!("无法写入 Claude Code 上下文插件 {}：{error}", dir.display()))?;
    }
    remove_stale(&parent, &name);
    materialized().lock().unwrap_or_else(|p| p.into_inner()).insert(root.to_owned(), dir.clone());
    Ok(dir)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn scratch(tag: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("mewrk-plugin-{tag}-{}", random_uuid()));
        fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    fn the_plugin_is_written_whole_and_replaces_stale_copies() {
        let root = scratch("write");
        let stale = root.join(PLUGINS_DIR).join(format!("{CONTEXT_PLUGIN_NAME}-0000000000000000"));
        fs::create_dir_all(&stale).unwrap();
        let staging = root.join(PLUGINS_DIR).join(format!(".{CONTEXT_PLUGIN_NAME}-1.crash"));
        fs::create_dir_all(&staging).unwrap();
        let unrelated = root.join(PLUGINS_DIR).join("unrelated");
        fs::create_dir_all(&unrelated).unwrap();

        let dir = context_plugin_dir(root.to_str().unwrap()).unwrap();
        assert!(is_complete(&dir));
        assert!(dir.file_name().unwrap().to_str().unwrap().starts_with("mewrk-context-"));
        assert!(!stale.exists() && !staging.exists() && unrelated.exists());
        assert!(fs::read_to_string(dir.join("hooks/context.ts")).unwrap().contains(r#"const PASSED = ["deferred_tools_delta"];"#));

        // A copy damaged after the first use is rewritten rather than trusted.
        fs::write(dir.join("hooks/context.ts"), "broken").unwrap();
        let again = context_plugin_dir(root.to_str().unwrap()).unwrap();
        assert_eq!(again, dir);
        assert!(is_complete(&dir));
        let _ = fs::remove_dir_all(root);
    }

    #[test]
    fn the_digest_is_the_typescript_one() {
        // `claude-context-plugin.ts`'s `DIGEST`, evaluated in Node.
        #[cfg(unix)]
        assert_eq!(digest(), "124478923aa82350");
    }
}
